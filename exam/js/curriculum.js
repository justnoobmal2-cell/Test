/* 헬퍼 */
const Curriculum = {
  subjects() {
    return Object.keys(CURRICULUM);
  },
  tracks(subject) {
    const rows = CURRICULUM[subject] || [];
    return [...new Set(rows.map(r => r.track))];
  },
  units(subject, track) {
    const rows = (CURRICULUM[subject] || []).filter(r => !track || r.track === track);
    return [...new Set(rows.map(r => r.unit))];
  },
  topics(subject, unit) {
    const row = (CURRICULUM[subject] || []).find(r => r.unit === unit);
    return row ? row.topics.slice() : [];
  },
  trackOfUnit(subject, unit) {
    const row = (CURRICULUM[subject] || []).find(r => r.unit === unit);
    return row ? row.track : "";
  },
  orgOf(examKey) {
    const e = EXAMS.find(e => e.key === examKey);
    return e ? e.org : "";
  }
};
